#pragma once

#include <maya/MDataBlock.h>
#include <maya/MMatrix.h>
#include <maya/MObject.h>
#include <maya/MPoint.h>
#include <maya/MVector.h>

#include <vector>

// Коллизия, общая для цепочки и для тряски.
//
// Обе ноды толкают точки из одних и тех же коллайдеров одними и теми же
// числами, и лежать это должно в одном месте: два плагина с одной нодой уже
// разъехались бы, если бы мы их не слили, а две копии коллизии в двух нодах
// разъедутся тем же способом - правку сделаешь в одной и забудешь про другую.
//
// Что снаружи: список коллайдеров, у каждого своя матрица, поэтому любой из них
// парентится и анимируется бесплатно. Плоскость смотрит своим Y и по умолчанию
// бесконечна; выключил infinite - стала квадратом своего размера. Сфера берёт
// радиус, капсула ещё и длину по своему Y, бокс - три стороны. Всё считается в
// собственной системе коллайдера, так что поворот и масштаб трансформа работают
// сами собой.
//
// У бокса, в отличие от плоскости, есть внутренность, и проверяется то, где
// точка есть, а не путь, которым она шла: бокс тоньше того, что точка проходит
// за шаг, она перепрыгивает целиком. Для пола нужна плоскость.
namespace pk
{
    struct Collider
    {
        short   type = 0;             // 0 plane, 1 sphere, 2 capsule, 3 box
        MPoint  o;                    // где он стоит
        MVector n;                    // плоскость: куда наружу; капсула: пол-оси
        double  radius = 0.0;
        bool    infinite = true;      // только плоскость
        MVector half;                 // половины сторон, в его системе
        MMatrix xf, inv;              // и сама система
    };

    // Всё, что нужно одному толчку: сколько коллизии подмешивать, как отдаётся
    // скорость, и кто вообще стоит на пути.
    struct World
    {
        double collide = 0.0, bounce = 0.0, friction = 0.0;
        std::vector<Collider> colliders;

        bool any() const { return collide > 1.0e-9 && !colliders.empty(); }
    };

    // Атрибуты, одинаковые у обеих нод. Создаются здесь, а добавляет их каждая
    // нода сама - addAttribute у MPxNode свой.
    struct Attrs
    {
        MObject collide, thickness, bounce, friction;
        MObject collider, type, infinite, size, sizeX, sizeY, sizeZ;
        MObject matrix, radius, length;
    };

    void make(Attrs& a);
    void list(const Attrs& a, std::vector<MObject>& out);
    // node нужен, чтобы спросить у графа, подключена ли матрица коллайдера:
    // элемент без связи - это мусор от удалённого коллайдера, и верить ему
    // нельзя, иначе на месте пола, которого больше нет, остаётся плоскость в
    // начале координат
    void read(MDataBlock& data, const Attrs& a, const MObject& node, World& w);

    // Насколько глубоко точка внутри и куда её оттуда.
    bool depthOf(const Collider& c, const MPoint& p, double pad,
                 MVector& dir, double& depth);

    // Одну точку наружу из всех коллайдеров сразу. vel даётся там, где толчок
    // должен чувствоваться - внутри симуляции; в конце кадра его не дают, там
    // надо только удержать. Возвращает true, если точку и правда сдвинуло: по
    // этому наружный цикл и решает, нужен ли ещё круг.
    bool clear(MPoint& p, MVector* vel, const World& w, double pad);

    // Сколько раз ходить по кругу, прежде чем считать, что дальше некуда:
    // точку, зажатую между двумя коллайдерами, второй загоняет обратно в
    // первый, и в углу между ними это занимает несколько заходов. Обычный
    // случай, когда ничто ничего не касается, стоит один просмотр и выходит.
    const int kRounds = 8;
}
